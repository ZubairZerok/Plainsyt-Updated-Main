export interface AIMessage {
  role: 'user' | 'assistant' | 'system';
  content: string;
}

export interface AIResponse {
  answer: string;
  source?: string;
  model: string;
  isOnline: boolean;
}

export async function queryPlainsytAI(
  userQuery: string,
  history: { role: 'user' | 'ai'; text: string }[] = []
): Promise<AIResponse> {
  const apiKey = getApiKey();

  // If API key is available, attempt remote query through OpenRouter models
  if (apiKey) {
    const messages: AIMessage[] = [
      { role: 'system', content: SYSTEM_PROMPT },
      ...history.slice(-8).map((m) => ({
        role: (m.role === 'ai' ? 'assistant' : 'user') as 'assistant' | 'user',
        content: m.text,
      })),
      { role: 'user', content: userQuery.trim() },
    ];

    for (const model of CANDIDATE_MODELS) {
      try {
        const response = await fetch('https://openrouter.ai/api/v1/chat/completions', {
          method: 'POST',
          headers: {
            Authorization: `Bearer ${apiKey}`,
            'Content-Type': 'application/json',
            'HTTP-Referer': 'https://pla.insyt.bd',
            'X-Title': 'PLAiNSYT Agro-Tech Bangladesh',
          },
          body: JSON.stringify({
            model,
            messages,
            temperature: 0.6,
            max_tokens: 1000,
          }),
        });

        if (response.ok) {
          const data = await response.json();
          const content = data?.choices?.[0]?.message?.content;
          if (content && typeof content === 'string' && content.trim().length > 0) {
            return {
              answer: content.trim(),
              model,
              isOnline: true,
            };
          }
        }
      } catch {
        // Try next candidate model
      }
    }
  }

  // Resilient fallback to ultra-trained local agronomy engine
  return {
    answer: getLocalAgronomyFallback(userQuery),
    model: 'plainsyt-agronomy-core',
    isOnline: false,
  };
}

